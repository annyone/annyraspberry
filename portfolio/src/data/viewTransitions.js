// Классы, помечающие части, которые переезжают при переходе «карточка
// на главной → страница кейса».
//
// Браузер сопоставляет элементы до и после перехода по view-transition-name:
// одинаковое имя означает, что это один и тот же элемент, и вместо
// растворения он переезжает на новое место и меняет размер. Отсюда три
// пары — подложка, заголовок и снимок экрана: подложка подъезжает к верху
// страницы и растягивается, заголовок встаёт в одну строку, снимок уходит
// под него на всю ширину. Описание карточки имени не получает: на странице
// кейса его нет, и оно просто растворяется.
//
// Имена объявлены классами в src/index.css, а не inline-стилями. Причина
// не в красоте: view-transition-name — свойство, которого нет в CSSOM
//jsdom, и запись через style молча теряется. В браузере всё работало бы,
// а проверить связку было бы нечем — тест не видел бы ни имени, ни его
// пропажи.
export const CASE_TRANSITION = {
  background: 'vt-case-background',
  title: 'vt-case-title',
  thumbnail: 'vt-case-thumbnail',
};

// Пустые строки вместо классов, когда перехода нет.
//
// Имя обязано быть уникальным на всю страницу в момент съёмки. Карточек
// на главной четыре, поэтому классы выдаются только той, на которую идёт
// переход: повесив их на все, браузер отказался бы анимировать вовсе.
const NONE = { background: '', title: '', thumbnail: '' };

export function caseTransitionNames(active = true) {
  return active ? CASE_TRANSITION : NONE;
}

export default caseTransitionNames;

// Шапка сайта.
//
// Своего переезда у неё нет — она одинакова по обе стороны перехода.
// Имя ей нужно ровно за тем, чтобы вынуть её из общего снимка страницы:
// без имени она попадает в снимок root, а он лежит НИЖЕ всех именованных
// частей, и разворачивающаяся подложка кейса накрывала логотип. С именем
// шапка становится отдельным слоем, которому в src/index.css задан
// z-index выше остальных.
export const NAV_TRANSITION = 'vt-site-nav';
